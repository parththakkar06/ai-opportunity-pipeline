"""Evaluate saved runs in outputs/ and write docs/eval_results.md (and, with --readme, the README table).

    python scripts/eval.py                       # similarity, verifier, tokens: no LLM calls
    python scripts/eval.py --judge               # + one cheap-model judge call per report (cached)
    python scripts/eval.py --embeddings gemini   # Gemini embeddings instead of TF-IDF (needs GEMINI_API_KEY)
    python scripts/eval.py --only sobha,adani-realty --readme

It never runs the pipeline; run `python run_pipeline.py "<Company>"` first for fresh outputs.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from dotenv import load_dotenv  # noqa: E402

from utils.costs import CostTracker  # noqa: E402
from utils.evals import (  # noqa: E402
    cross_company_similarity, gemini_embeddings, judge_run, judge_weighted, load_runs, opportunity_texts,
    results_markdown, run_metrics, write_readme_section,
)


def main(argv: list[str] | None = None, llm=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--outputs", type=Path, default=ROOT / "outputs")
    p.add_argument("--only", help="Comma-separated run folders (slugs) to include")
    p.add_argument("--judge", action="store_true", help="Score each report with the cheap model (1 call each, cached)")
    p.add_argument("--refresh-judge", action="store_true", help="Ignore cached judge scores")
    p.add_argument("--embeddings", choices=["tfidf", "gemini"], default="tfidf")
    p.add_argument("--out", type=Path, default=ROOT / "docs" / "eval_results.md")
    p.add_argument("--readme", action="store_true", help="Also update the table in README.md")
    args = p.parse_args(argv)
    load_dotenv(ROOT / ".env")

    runs, skipped = load_runs(args.outputs, args.only.split(",") if args.only else None)
    if not runs:
        print("No completed runs found in", args.outputs, "-", "; ".join(skipped) or "folder is empty")
        return 1

    texts = {r.slug: opportunity_texts(r.report) for r in runs}
    method, vectors = "TF-IDF cosine, no API calls", None
    if args.embeddings == "gemini":
        key = os.getenv("GEMINI_API_KEY")
        model = os.getenv("EVAL_EMBED_MODEL", "gemini-embedding-001")
        if key:
            try:
                vectors = gemini_embeddings([t for s in texts for t in texts[s]], key, model)
                method = f"Gemini `{model}` embeddings"
            except Exception as exc:  # noqa: BLE001
                print(f"Gemini embeddings failed ({exc.__class__.__name__}); using TF-IDF instead.")
        else:
            print("GEMINI_API_KEY isn't set; using TF-IDF instead.")
    similarity = cross_company_similarity(texts, vectors)

    judged, judge_model, tracker = {}, None, CostTracker()
    if args.judge:
        from utils.config import load_settings
        from utils.llm import build_llm

        settings = load_settings()
        llm = llm or build_llm(settings, tracker)
        judge_model = settings.cheap_model
        system = (ROOT / "prompts" / "eval_judge.md").read_text()
        for r in runs:
            try:
                scores, cached = judge_run(r, llm, judge_model, system, refresh=args.refresh_judge)
                judged[r.slug] = scores
                print(f"judge {r.slug}: {judge_weighted(scores)}/100" + (" (cached)" if cached else ""))
            except Exception as exc:  # noqa: BLE001 - one failed judgment shouldn't lose the rest
                print(f"judge {r.slug}: failed ({str(exc)[:120]})")

    table = results_markdown(runs, similarity, method, judged, judge_model, skipped)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("# Evaluation results\n\nGenerated by `python scripts/eval.py`"
                        + (" --judge" if args.judge else "") + ".\n\n" + table, encoding="utf-8")
    data = {"similarity": similarity, "similarity_method": method, "judge_model": judge_model,
            "runs": {r.slug: {**run_metrics(r), "legacy": r.legacy,
                              "judge": judged[r.slug].model_dump() if r.slug in judged else None,
                              "judge_score": judge_weighted(judged[r.slug]) if r.slug in judged else None}
                     for r in runs},
            "judge_tokens": {"input": tracker.total().input_tokens, "output": tracker.total().output_tokens}}
    args.out.with_suffix(".json").write_text(json.dumps(data, indent=2), encoding="utf-8")
    if args.readme:
        write_readme_section(ROOT / "README.md", table)
    print(table)
    print(f"Wrote {args.out}" + (" and README.md" if args.readme else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
